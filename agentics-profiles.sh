#!/usr/bin/env bash
# Gives each repo of the container its agentics profile. The commit lock is claude-ask-rules.sh.
# Usage: agentics-profiles.sh [workspaces folder, default /workspaces]
# A profile is agentics/profiles/<repo>.yaml in this dotfiles repo. It is copied to the repo root once, as
# agentics.container.yaml, and hidden from git through .git/info/exclude: a file of this clone (the host's
# clone too, as the folder is shared), never committed, so the team's .gitignore is untouched. Its own name, because the repo folder is shared with the host: its paths
# (/home/vscode/...) are the container's, and a host agentics.yaml with host paths must not be mixed up with it.
set -euo pipefail

workspaces="${1:-/workspaces}"
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
profiles="${AGENTICS_PROFILES:-$here/agentics/profiles}"
kernel="${AGENTICS_DIR:-$HOME/agentics}/agentics"
name=agentics.container.yaml

exclude_in() {  # exclude_in <repo> <pattern>...: add each pattern to the repo's own info/exclude, once
  local repo=$1 exclude path; shift
  exclude="$(git -C "$repo" rev-parse --git-path info/exclude)"
  case "$exclude" in /*) ;; *) exclude="$repo/$exclude" ;; esac
  mkdir -p "$(dirname "$exclude")"
  # A last line without its newline would swallow the first pattern appended.
  if [ -s "$exclude" ] && [ -n "$(tail -c1 "$exclude")" ]; then echo >> "$exclude"; fi
  for path in "$@"; do
    grep -qxF "$path" "$exclude" 2> /dev/null || echo "$path" >> "$exclude"
  done
}

# One repo git cannot read (a host worktree whose .git points to a host path, a folder another user owns)
# must not stop the whole install: it is skipped, and git's own reason is printed, not hidden.
declare -A skipped=()
usable() {  # usable <repo>: the repo's own root (a plain folder inside a parent repo passes
            # `rev-parse --is-inside-work-tree`), and git can read it
  local repo=$1 why
  [ -e "$repo/.git" ] || return 1
  [ -z "${skipped[$repo]:-}" ] || return 1
  if ! why="$(git -C "$repo" rev-parse --git-dir 2>&1 > /dev/null)"; then
    echo "   warning: skipped $repo: ${why:-git cannot read it}" >&2
    skipped[$repo]=1
    return 1
  fi
}

# Every repo, with a profile here or not: a container profile made by hand must never reach a team commit,
# nor what it writes in the repo. .agentics/: role rules (`roles.<role>.rules`, as in the kernel's demos);
# .agentic/ and agentic-reports/: knowledge base and reports of the starter profile `agentics init` writes.
# The .git folder is the host's too: these patterns also disappear from `git status` on the host. Intended.
for repo in "$workspaces"/*/; do
  repo="${repo%/}"
  if usable "$repo"; then exclude_in "$repo" "$name" "$name.generated*" .agentics/ .agentic/ agentic-reports/; fi
done

# A .NET repo with no dotfiles profile gets one learned from the hand-written ones (erp-socle, gmao-referential,
# Facturette, Shopify_2, system-trade-2; 2026-11-15). The fast suite leaves out what needs Docker: each project that
# references Testcontainers (itself, through its Directory.Build.props, or through a project it references), by its
# namespace (the name and what is below it: `Name*` would also take NameKernel). Only when that is safe; otherwise
# the fast suite is the whole one (the kernel's `check` refuses a profile without one), and every run says why.
# VSTest filters only by "contains", which cannot keep a Docker project's namespace apart from others: there, only
# the Integration trait. Not learned: a hand-picked list (Facturette's), a trait spelled through a constant, a
# namespace the code declares other than its project's. Such a profile is written by hand in agentics/profiles/. It is a
# guess: one the kernel refuses is a warning, never the end of the install.
marker='# Generated by agentics-profiles.sh'
whole_because='# Fast suite: the whole one, because'
docker_ref='<PackageReference[^>]*Include="(DotNet\.)?Testcontainers'
test_attr='\[(Fact|Theory|Test|TestCase|TestMethod|DataTestMethod)\b'
# Build output, packages, and hidden folders: a worktree under .claude/ or .git/ is a copy, not a project.
skip=(--exclude-dir=bin --exclude-dir=obj --exclude-dir=node_modules --exclude-dir='.?*')
msbuild_text() {  # msbuild_text <file>: without its comments, on one line (an element may span several)
  awk 'BEGIN { RS = "<!--" } NR == 1 { printf "%s", $0; next }
       { i = index($0, "-->"); if (i) printf "%s", substr($0, i + 3) }' "$1" | tr '\n' ' '
}
conditional_docker() {  # conditional_docker <text>: a Testcontainers reference with a Condition on it or its ItemGroup
  awk 'BEGIN { RS = "</[Ii][Tt][Ee][Mm][Gg][Rr][Oo][Uu][Pp]>" }
       { r = tolower($0); p = 0; s = r
         while ((i = index(s, "<itemgroup")) > 0) { p += i; s = substr(s, i + 1) }
         blk = p ? substr(r, p) : r; tag = p ? substr(blk, 1, index(blk, ">")) : ""
         if (blk ~ /<packagereference[^>]*include="(dotnet\.)?testcontainers/ && (tag ~ /condition/ \
             || blk ~ /<packagereference[^>]*condition[^>]*include="(dotnet\.)?testcontainers/ \
             || blk ~ /<packagereference[^>]*include="(dotnet\.)?testcontainers[^>]*condition/)) found = 1 }
       END { exit !found }' <<< "$1"
}
is_test() {  # is_test <project name>: by name, as in every repo seen. Not *test*: Latest or Attestation is code.
  case "$1" in *Tests | *Test | Test[A-Z]* | *Tests.* | *.Test.* | *.Testing | *.Testing.*) return 0 ;; esac
  return 1
}
name_of() { local n=${1##*/}; echo "${n%.csproj}"; }  # name_of <csproj path>
msbuild_namespace() {  # msbuild_namespace <name>: as MSBuild derives it: a non-identifier character as _, and _
                       # before a segment that starts with a digit
  local n=${1//[^A-Za-z0-9_.]/_} out= seg
  while IFS= read -r -d . seg; do
    case "$seg" in [0-9]*) seg=_$seg ;; esac
    out+=${out:+.}$seg
  done <<< "$n."
  echo "$out"
}
generate() {  # generate <repo>: print the profile; when there is none to learn, print why and fail
  local repo=$1 sln sols projects rel ref inc d text root fast suite parser changed runnable=0 why= ns_why= ref_why= ns build
  local -a code=() test_paths=() sources=() excludes=()
  local -A docker=() refs=() props_docker=() props_import=() has_test=() nsof=()
  mapfile -t sols < <(cd "$repo" && ls -- *.slnx *.sln 2> /dev/null)
  case ${#sols[@]} in
    0) return 1 ;;  # not a .NET repo: nothing to say, on every run
    1) sln=${sols[0]} ;;
    *) echo "more than one solution at its root, and \`dotnet test\` alone cannot choose"; return 1 ;;
  esac
  # Both end up between double quotes, in YAML and in a test command the kernel splits and screens for operators.
  case "$(basename "$repo")/$sln" in
    *[\"\\\;\|\<\>\`\$\&\(\)]*) echo "a quote, a backslash or a shell character in its name or its solution's"; return 1 ;;
  esac
  projects="$(cd "$repo" && find . -type d \( -name '.?*' -o -name bin -o -name obj -o -name node_modules \) -prune \
    -o -name '*.csproj' -print | sed 's#^\./##' | sort)"
  # Project folders go between double quotes in the YAML globs.
  if grep -F -e '"' -e '\' <<< "$projects" > /dev/null; then echo "a quote or a backslash in a project path"; return 1; fi

  # Each project file read once, projects told apart by path (two folders may hold one name): its references, its
  # namespace, and Docker through its own reference or its nearest Directory.Build.props (the only one MSBuild
  # imports, read once per folder). A reference behind a Condition there, or a RootNamespace set there, cannot be
  # resolved here. Then each project that references a Docker one, until none is added.
  while read -r rel; do
    [ -n "$rel" ] || continue
    text=$(msbuild_text "$repo/$rel")
    refs[$rel]=
    while read -r inc; do
      [ -n "$inc" ] || continue
      case "$inc" in *'$('*) ref_why="a ProjectReference through an MSBuild property in $rel"; continue ;; esac
      refs[$rel]+="$(realpath -m --relative-to="$repo" "$repo/$(dirname "$rel")/${inc//\\//}")"$'\n'
    done < <(grep -oE '<ProjectReference[^>]*Include="[^"]+\.csproj"' <<< "$text" \
      | sed -E 's#.*Include="([^"]+)"$#\1#' || true)
    ns=$(grep -oE '<RootNamespace>[^<]*</RootNamespace>' <<< "$text" | sed -E 's#<[^>]*>##g' | tail -1 || true)
    case "$ns" in *'$'*) ns_why="a RootNamespace computed in $rel" ;; esac
    nsof[$rel]=$(msbuild_namespace "${ns:-$(name_of "$rel")}")
    if grep -iE "$docker_ref" <<< "$text" > /dev/null; then docker[$rel]=1; fi
    # The nearest Directory.Build.props, and each one above it that it imports.
    d=$(dirname "$rel")
    while :; do
      while [ ! -e "$repo/$d/Directory.Build.props" ] && [ "$d" != . ]; do d=$(dirname "$d"); done
      [ -e "$repo/$d/Directory.Build.props" ] || break
      if [ -z "${props_docker[$d]:-}" ]; then
        props_docker[$d]=0
        text=$(msbuild_text "$repo/$d/Directory.Build.props")
        if grep -iE "$docker_ref" <<< "$text" > /dev/null; then
          if conditional_docker "$text"; then  # which projects it reaches is not knowable here: none marked
            props_docker[$d]=c
            why="a Testcontainers reference behind a Condition in $d/Directory.Build.props"
          else
            props_docker[$d]=1
          fi
        fi
        if grep -F '<RootNamespace>' <<< "$text" > /dev/null; then
          ns_why="a RootNamespace set in $d/Directory.Build.props"
        fi
        props_import[$d]=0
        if grep -E '<Import[[:space:]][^>]*Directory\.Build\.props' <<< "$text" > /dev/null; then props_import[$d]=1; fi
      fi
      if [ "${props_docker[$d]}" = 1 ]; then docker[$rel]=1; fi
      [ "${props_import[$d]}" = 1 ] && [ "$d" != . ] || break
      d=$(dirname "$d")
    done
  done <<< "$projects"
  changed=1
  while [ "$changed" = 1 ]; do
    changed=0
    for rel in "${!refs[@]}"; do
      [ -z "${docker[$rel]:-}" ] || continue
      while read -r ref; do
        if [ -n "$ref" ] && [ -n "${docker[$ref]:-}" ]; then docker[$rel]=1; changed=1; break; fi
      done <<< "${refs[$rel]}"
    done
  done

  # Which project a test method belongs to: the nearest folder above it with a project file (a project nested in
  # another one keeps its tests to itself).
  while read -r d; do  # each folder holding a test file, once
    until [ "$d" = . ] || compgen -G "$repo/$d/*.csproj" > /dev/null; do d=$(dirname "$d"); done
    has_test[$d]=1
  done < <(cd "$repo" && grep -rlE --include='*.cs' "${skip[@]}" "$test_attr" . \
    | sed -E 's#^\./##; s#/[^/]*$##; s#^[^/]*\.cs$#.#' | sort -u || true)

  # A test project: a test name, Docker (no production code starts a container), or a test method in it, whatever
  # its name. The ones the fast suite would still run: no Docker, and a test in them (a test-named helper has none).
  while read -r rel; do
    [ -n "$rel" ] || continue
    if is_test "$(name_of "$rel")" || [ -n "${docker[$rel]:-}" ] || [ -n "${has_test[$(dirname "$rel")]:-}" ]; then
      test_paths+=("$rel")
      if [ -z "${docker[$rel]:-}" ] && [ -n "${has_test[$(dirname "$rel")]:-}" ]; then runnable=$((runnable + 1)); fi
    else
      code+=("$rel")
    fi
  done <<< "$projects"
  [ ${#code[@]} -gt 0 ] || { echo "no project outside the tests"; return 1; }
  for rel in "${test_paths[@]}"; do
    [ "${rel%/*}" != "$rel" ] || { echo "a test project at its root, inside every source glob"; return 1; }
  done
  # src/** when src/ holds all the code, as in the hand-written profiles; otherwise each code project's own folder
  # (a grouping folder would take the tests next to it). A test folder inside a glob is excluded from it.
  if ! printf '%s\n' "${code[@]}" | grep -v '^src/' > /dev/null; then
    sources=("src/**/*.cs")
  else
    for rel in "${code[@]}"; do
      case "$rel" in */*) sources+=("${rel%/*}/**/*.cs") ;; *) sources+=("**/*.cs") ;; esac
    done
  fi
  for rel in "${test_paths[@]}"; do
    d=${rel%/*}
    for root in "${sources[@]}"; do
      root=${root%\*\*/\*.cs}  # "src/", "Api/", or "" for a project at the root: everything
      case "$d/" in "$root"*) excludes+=("$d/**"); break ;; esac
    done
  done

  # The test frameworks and the MTP switch the build files name, in one pass.
  # From inside the repo: --exclude-dir='.?*' would also match a hidden folder above it, named on the command line.
  build=$(cd "$repo" && grep -rhoiE --include='*.csproj' --include='*.props' "${skip[@]}" \
    'Include="(xunit\.v3|MSTest|NUnit|TUnit)|<TestingPlatformDotnetTestSupport>[[:space:]]*true' . \
    | tr '[:upper:]' '[:lower:]' | sort -u || true)
  # A namespace or a reference this script cannot resolve matters only if some project needs Docker.
  if [ -z "$why" ] && [ ${#docker[@]} -gt 0 ]; then why=${ns_why:-$ref_why}; fi
  # The whole suite. `dotnet test` alone refuses a folder with a project next to the solution (MSB1011): named then.
  suite="dotnet test"
  if printf '%s\n' "${code[@]}" "${test_paths[@]}" | grep -v / > /dev/null; then suite="dotnet test \\\"$sln\\\""; fi
  fast=$suite
  # A grep, not jq: the SDK reads global.json with comments and trailing commas, jq refuses them.
  if grep -qE '"runner"[[:space:]]*:[[:space:]]*"Microsoft\.Testing\.Platform"' "$repo/global.json" 2> /dev/null; then
    parser=mtp
    # MTP mode takes the solution through --solution only.
    if [ "$suite" != "dotnet test" ]; then suite="dotnet test --solution \\\"$sln\\\""; fast=$suite; fi
    if [ ${#docker[@]} -gt 0 ] && [ -z "$why" ]; then
      if [ "$runnable" -eq 0 ]; then
        why="no test runs without Docker"
      elif ! grep -F 'include="xunit.v3' <<< "$build" > /dev/null; then
        why="no xunit v3, whose option --filter-not-namespace is"
      elif grep -E 'include="(mstest|nunit|tunit)' <<< "$build" > /dev/null; then
        why="a test framework other than xunit v3, which refuses --filter-not-namespace"
      fi
      for rel in "${!refs[@]}"; do  # a project without Docker inside a Docker project's namespace
        [ -z "$why" ] && [ -z "${docker[$rel]:-}" ] || continue
        for ref in "${!docker[@]}"; do
          case "${nsof[$rel]}" in "${nsof[$ref]}" | "${nsof[$ref]}".*) why="$rel shares the namespace of a Docker project" ;; esac
        done
      done
      if [ -z "$why" ]; then
        fast="dotnet test --solution \\\"$sln\\\""
        while read -r ns; do
          fast+=" --filter-not-namespace \\\"$ns\\\" --filter-not-namespace \\\"$ns.*\\\""
        done < <(for rel in "${!docker[@]}"; do echo "${nsof[$rel]}"; done | LC_ALL=C sort -u)
        fast+=" --ignore-exit-code 8"
      fi
    fi
  elif grep -F '<testingplatformdotnettestsupport>' <<< "$build" > /dev/null; then
    parser=mtp
    if [ ${#docker[@]} -gt 0 ]; then
      why="MTP through TestingPlatformDotnetTestSupport, whose options go through \`--\`: not generated"
    fi
  else
    parser=xunit
    if [ ${#docker[@]} -gt 0 ]; then
      why="VSTest filters by \"contains\" only, which cannot keep a Docker project apart"
    elif [ -z "$why" ] && (cd "$repo" && grep -rqiE --include='*.cs' "${skip[@]}" \
      'Trait\(\s*"Category"\s*,\s*"Integration"\s*\)' .); then
      # One clause for every spelling: "All the lookups are case insensitive"
      # (learn.microsoft.com/dotnet/core/testing/selective-unit-tests).
      fast="$suite --filter \\\"Category!=Integration\\\""
    fi
  fi
  echo "$marker: no dotfiles profile for this repo. Edit it here, or move it to"
  echo "# agentics/profiles/$(basename "$repo").yaml in the dotfiles to keep it across containers."
  if [ "$fast" = "$suite" ] && [ -n "$why" ]; then echo "$whole_because $why"; fi
  echo "name: \"$(basename "$repo")\""
  echo "project:"
  echo "  root: ."
  echo "  source_globs:"
  printf '    - "%s"\n' "${sources[@]}" | sort -u
  echo "  exclude:"
  printf '    - "%s"\n' "**/bin/**" "**/obj/**" "**/Migrations/**" "**/*.g.cs" "**/*.Designer.cs" "**/node_modules/**"
  [ ${#excludes[@]} -eq 0 ] || printf '    - "%s"\n' "${excludes[@]}" | sort -u
  echo "tests:"
  echo "  authoritative: \"$suite\""
  echo "  fast: \"$fast\""
  echo "  parser: $parser"
  echo "security:"
  printf '  - %s\n' auth token secret password permission "personal data"
  echo "knowledge_base: \"$HOME/secondbrain\""
  echo "reports: \"$HOME/agentics-reports/$(basename "$repo")\""
}

failed=()
is_generated() { head -1 "$1" | grep -qF "$marker"; }  # is_generated <profile>: written by generate, not by hand
kernel_ok() {  # kernel_ok <repo>: the kernel's init and check pass on the repo's profile
  "$kernel" init --project "$1/$name" && "$kernel" check --project "$1/$name"
}

# Repos with no dotfiles profile. A generated profile goes through the kernel on every run, like a dotfiles one: a
# check that failed once must not pass unseen on the next run. A profile made by hand there is left alone, as it
# always was: it is the user's, not this script's, to keep passing the kernel.
for repo in "$workspaces"/*/; do
  repo="${repo%/}"
  [ ! -e "$profiles/$(basename "$repo").yaml" ] || continue
  usable "$repo" || continue
  if [ ! -e "$repo/$name" ]; then
    if ! profile="$(generate "$repo")"; then
      [ -z "$profile" ] || echo "   note: $repo: $profile: no profile generated"
      continue
    fi
    # A repo git reads but this user cannot write to: skipped like one git cannot read, never the end of the install,
    # with the system's own reason.
    if ! err=$( { printf '%s\n' "$profile" > "$repo/$name"; } 2>&1 ); then
      echo "   warning: skipped $repo: cannot write $repo/$name: ${err##*: }" >&2
      continue
    fi
    echo "-- generated $repo/$name"
  fi
  is_generated "$repo/$name" || continue
  # Why its fast suite is the whole one, and a guess the kernel refuses: said on every run, but the install goes on.
  why=$(sed -n "s/^$whole_because //p" "$repo/$name")
  # Only while the fast suite is still the whole one: an edited fast line makes the reason stale.
  if [ -n "$why" ] && [ "$(sed -n 's/^  fast: //p' "$repo/$name")" = "$(sed -n 's/^  authoritative: //p' "$repo/$name")" ]; then
    echo "   note: $repo: the fast suite is the whole one: $why"
  fi
  kernel_ok "$repo" \
    || echo "   warning: the kernel refused the generated $repo/$name: edit it, or add agentics/profiles/$(basename "$repo").yaml to the dotfiles" >&2
done

for profile in "$profiles"/*.yaml; do
  [ -e "$profile" ] || continue
  repo="$workspaces/$(basename "$profile" .yaml)"
  usable "$repo" || continue
  echo "-- agentics profile for $repo"

  # The profiles say /home/vscode, the remoteUser of the team's dev containers: make it this container's $HOME.
  rendered="$(mktemp)"
  sed "s#/home/vscode#$HOME#g" "$profile" > "$rendered"
  # Never overwrite: the copy in the repo may hold a local edit. Say so, or a fix to the profile here is lost silently.
  if [ ! -e "$repo/$name" ]; then
    cp "$rendered" "$repo/$name"
  elif is_generated "$repo/$name"; then
    # A guess made while there was no dotfiles profile: the dotfiles one is meant to replace it. A copy is kept aside,
    # in case it was edited here, never over an earlier one. Copies, not a move: the generated profile stays in place
    # until the dotfiles one is written, and a failure takes the copy back.
    aside="$repo/$name.generated"
    err=
    if [ -e "$aside" ] && ! aside=$(mktemp "$aside.XXXXXX" 2>&1); then
      err=$aside; aside=
    elif ! err=$(cp "$repo/$name" "$aside" 2>&1); then
      rm -f "$aside"
    elif ! err=$(cp "$rendered" "$repo/$name" 2>&1); then
      if cmp -s "$aside" "$repo/$name" || cp "$aside" "$repo/$name" 2> /dev/null; then
        rm -f "$aside"
      else
        err+=" (the generated profile is in $aside)"
      fi
    else
      err=
    fi
    if [ -n "$err" ]; then
      echo "   warning: skipped $repo: cannot replace its generated $name: ${err##*: }" >&2
      rm -f "$rendered"
      continue
    fi
    echo "   note: the dotfiles profile replaces the generated one, kept as $aside"
  elif ! cmp -s "$rendered" "$repo/$name"; then
    echo "   note: $repo/$name differs from $profile; the repo copy is kept"
  fi
  rm -f "$rendered"

  # One repo the kernel refuses must not leave the repos after it unset: carry on, and fail at the end.
  kernel_ok "$repo" || failed+=("$repo")
done
if [ ${#failed[@]} -gt 0 ]; then
  echo "error: agentics init/check failed for: ${failed[*]}" >&2
  exit 1
fi
